#!/usr/bin/env python3
"""Convert UTF-8 TSV or ECDICT CSV into uncompressed plain-text StarDict."""
import argparse
import csv
import json
import struct
from pathlib import Path


def sort_key(word):
    raw = word.encode("utf-8")
    folded = bytes(c + 32 if 65 <= c <= 90 else c for c in raw)
    return folded, raw


def load_tsv(path):
    entries = {}
    for number, line in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            raise ValueError(f"line {number}: expected word<TAB>definition")
        word, meaning = line.split("\t", 1)
        if word in entries:
            entries[word] += "\n\n" + meaning.replace("\\n", "\n")
        else:
            entries[word] = meaning.replace("\\n", "\n")
    return entries


def load_ecdict(path):
    entries = {}
    with Path(path).open(encoding="utf-8-sig", newline="") as stream:
        for row in csv.DictReader(stream, strict=True):
            word = row["word"].strip()
            meaning = (row.get("translation") or row.get("definition") or "").strip()
            if not word or not meaning or len(word.encode("utf-8")) > 255:
                continue
            parts = []
            if row.get("phonetic"):
                parts.append("/" + row["phonetic"] + "/")
            parts.append(meaning.replace("\\n", "\n").replace("\\r", ""))
            if row.get("exchange"):
                labels = {"p": "过去式", "d": "过去分词", "i": "现在分词", "3": "第三人称", "s": "复数", "r": "比较级", "t": "最高级", "0": "原形"}
                forms = []
                for item in row["exchange"].split("/"):
                    if ":" in item:
                        code, form = item.split(":", 1)
                        if code in labels:
                            forms.append(labels[code] + ": " + form)
                if forms:
                    parts.append("\n" + "\n".join(forms))
            entries[word] = "\n".join(parts)
    return entries


def write_stardict(entries, prefix, name):
    prefix = Path(prefix)
    prefix.parent.mkdir(parents=True, exist_ok=True)
    index = bytearray()
    offset = 0
    ordered = sorted(entries.items(), key=lambda item: sort_key(item[0]))
    if not ordered or len(ordered) > 1_000_000:
        raise ValueError("Expected 1..1000000 headwords")
    with prefix.with_suffix(".dict").open("wb") as body:
        for word, meaning in ordered:
            encoded = word.encode("utf-8")
            text = meaning.encode("utf-8")
            if not encoded or len(encoded) > 255 or b"\0" in encoded or b"\0" in text:
                raise ValueError(f"Invalid word or NUL in content: {word!r}")
            index.extend(encoded + b"\0" + struct.pack(">II", offset, len(text)))
            body.write(text)
            offset += len(text)
            if offset > 0xFFFFFFFF:
                raise ValueError("Dictionary exceeds 32-bit offsets")
    prefix.with_suffix(".idx").write_bytes(index)
    prefix.with_suffix(".ifo").write_text(
        "StarDict's dict ifo file\nversion=2.4.2\n"
        f"wordcount={len(ordered)}\nidxfilesize={len(index)}\nbookname={name}\n"
        "sametypesequence=m\n", encoding="utf-8")
    return {"words": len(ordered), "index_bytes": len(index), "body_bytes": offset}


def write_demo_header(entries, target):
    lines = ["// Generated by tools/prepare_dictionary.py; original demo content.", "#pragma once", "struct DemoEntry { const char* word; const char* text; };", "inline const DemoEntry kDemo[] = {"]
    for word, text in sorted(entries.items(), key=lambda item: sort_key(item[0])):
        lines.append("    {" + json.dumps(word, ensure_ascii=False) + ", " + json.dumps(text, ensure_ascii=False) + "},")
    lines.extend(["};", "inline constexpr size_t kDemoCount = sizeof(kDemo) / sizeof(kDemo[0]);", ""])
    Path(target).write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path, help="Output prefix, without extension")
    parser.add_argument("--format", choices=("tsv", "ecdict"), default="tsv")
    parser.add_argument("--name", default="Cardputer Dictionary")
    parser.add_argument("--demo-header", type=Path)
    args = parser.parse_args()
    entries = load_ecdict(args.input) if args.format == "ecdict" else load_tsv(args.input)
    print(json.dumps(write_stardict(entries, args.output, args.name), ensure_ascii=False))
    if args.demo_header:
        write_demo_header(entries, args.demo_header)


if __name__ == "__main__":
    main()
